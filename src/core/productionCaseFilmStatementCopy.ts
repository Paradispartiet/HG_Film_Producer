export function presentVerifiedFilmStatement(
  language: FilmWorkLanguage,
  briefType: ProductionCaseBriefType,
  scenarioId: string,
  original: string,
): string {
  if (briefType !== "production_case") return original;
  if (scenarioId === VERIFIED_SCENARIO_ID) {
    const presentation = statements[language];
    return Object.prototype.hasOwnProperty.call(presentation, original)
      ? presentation[original as TwelveAngryMenStatement]
      : original;
  }
  if (scenarioId === "scenario_the_machinist_2004") {
    const presentation = machinistStatements[language];
    return Object.prototype.hasOwnProperty.call(presentation, original)
      ? presentation[original as MachinistStatement]
      : original;
  }
  if (scenarioId === "scenario_vertigo_1958") {
    return presentVertigoProductionStatement(language, original);
  }
  if (scenarioId === "scenario_bicycle_thieves_1948") {
    if (language === "en") return original;
    const translated = bicycleThievesPresentation.get(original);
    return translated?.[language === "nb" ? 0 : language === "fr" ? 1 : 2] ?? original;
  }
  if (scenarioId === "scenario_lost_in_translation_2003") {
    if (language === "en") return original;
    const translated = lostInTranslationPresentation.get(original);
    return translated?.[language === "nb" ? 0 : language === "fr" ? 1 : 2] ?? original;
  }
  if (scenarioId === "scenario_the_lives_of_others_2006") {
    const presentation = livesStatements[language];
    return Object.prototype.hasOwnProperty.call(presentation, original)
      ? presentation[original as LivesOfOthersStatement]
      : original;
  }
  return original;
}

/** Shared read-only presentation resolver. Original corpus and storage remain untouched. */
export function presentFilmCaseContent(
  language: FilmWorkLanguage,
  briefType: ProductionCaseBriefType,
  scenarioId: string,
  original: string,
): string {
  return briefType === "seed_fallback"
    ? presentSeedFallbackText(language, briefType, original)
    : presentVerifiedFilmStatement(language, briefType, scenarioId, original);
}
